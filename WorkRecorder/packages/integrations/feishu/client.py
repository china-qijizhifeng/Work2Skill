logger = logging.getLogger(__name__)

FEISHU_SECRET_SERVICE = "app.workrecorder.feishu"
FEISHU_SECRET_ACCOUNT = "WORKRECORDER_FEISHU_APP_SECRET"


class FeishuIntegrationError(RuntimeError):
    """Sanitized Feishu failure that never contains app secrets or tokens."""

    def __init__(self, message: str, *, code: str = "feishu_error", retryable: bool = False) -> None:
        super().__init__(message)
        self.code = code
        self.retryable = retryable


MAX_PUBLISH_ATTEMPTS = 3
MAX_FEISHU_DOWNLOAD_BYTES = 15 * 1024 * 1024
T = TypeVar("T")
_URL_RE = re.compile(r"https?://\S+")
_LOCAL_PATH_RE = re.compile(r"(?<![\w/])(?:/Users|/private|/tmp|/var/folders)/\S+")


@dataclass
class _CachedTenantToken:
    value: str
    expires_at: datetime


class FeishuTokenClient:
    """Fetch and cache Feishu tenant access tokens."""

    def __init__(
        self,
        *,
        app_id: str | None,
        secret_store: SecretStore,
        api_base_url: str = "https://open.feishu.cn",
        clock: Clock,
    ) -> None:
        self.app_id = app_id
        self.secret_store = secret_store
        self.api_base_url = api_base_url.rstrip("/")
        self.clock = clock
        self._cached: _CachedTenantToken | None = None

    def tenant_access_token(self) -> str:
        """Return a valid tenant token or raise a sanitized config error.

        Returns:
            Cached or freshly fetched tenant access token.

        Raises:
            FeishuIntegrationError: If config is missing or Feishu rejects the request.
        """

        now = self.clock.now()
        if self._cached is not None and self._cached.expires_at > now + timedelta(seconds=60):
            return self._cached.value
        if not self.app_id:
            raise FeishuIntegrationError("Feishu app id is not configured.", code="config_missing")
        app_secret = self.secret_store.get(service=FEISHU_SECRET_SERVICE, account=FEISHU_SECRET_ACCOUNT)
        if not app_secret:
            raise FeishuIntegrationError("Feishu app secret is not configured.", code="secret_missing")
        try:
            response = httpx.post(
                f"{self.api_base_url}/open-apis/auth/v3/tenant_access_token/internal",
                json={"app_id": self.app_id, "app_secret": app_secret},
                timeout=10,
            )
            response.raise_for_status()
            payload = response.json()
        except (httpx.HTTPError, ValueError) as exc:
            raise FeishuIntegrationError(
                "Feishu tenant token request failed.", code="token_http", retryable=True
            ) from exc
        code = payload.get("code")
        if code != 0:
            raise FeishuIntegrationError(
                "Feishu tenant token was rejected.",
                code=f"feishu_{code}",
                retryable=code in {99991400, 99991663},
            )
        token = payload.get("tenant_access_token")
        if not isinstance(token, str) or not token:
            raise FeishuIntegrationError("Feishu token response was malformed.", code="token_malformed")
        expire_seconds = int(payload.get("expire", 7200) or 7200)
        self._cached = _CachedTenantToken(value=token, expires_at=now + timedelta(seconds=expire_seconds))
        return token


class FeishuDriveClient:
    """Typed wrapper around the Feishu Drive APIs used by share publishing."""

    def __init__(self, *, token_client: FeishuTokenClient, folder_token: str | None, api_base_url: str) -> None:
        self.token_client = token_client
        self.folder_token = folder_token
        self.api_base_url = api_base_url.rstrip("/")

    def upload_html(self, *, file_name: str, content: bytes) -> str:
        """Upload one static HTML share page and return its Feishu file token.

        Args:
            file_name: Sanitized file name for the uploaded HTML page.
            content: HTML bytes generated by the share package builder.

        Returns:
            Feishu file token used for permissions and URL lookup.

        Raises:
            FeishuIntegrationError: If upload fails, is rejected, or response is malformed.
        """

        if not content:
            raise FeishuIntegrationError("Share package is empty.", code="empty_upload")
        if self.folder_token:
            return self._upload_html_to_folder(
                file_name=file_name,
                content=content,
                folder_token=self.folder_token,
            )
        return self._upload_html_to_folder(
            file_name=file_name,
            content=content,
            folder_token=self.root_folder_token(),
        )

    def _upload_html_to_folder(self, *, file_name: str, content: bytes, folder_token: str) -> str:
        """Upload one HTML file to a concrete Drive folder token."""

        headers = self._headers()
        try:
            response = httpx.post(
                f"{self.api_base_url}/open-apis/drive/v1/files/upload_all",
                headers=headers,
                data={
                    "file_name": file_name,
                    "parent_type": "explorer",
                    "parent_node": folder_token,
                    "size": str(len(content)),
                },
                files={"file": (file_name, content, "text/html; charset=utf-8")},
                timeout=30,
            )
        except httpx.HTTPError as exc:
            raise FeishuIntegrationError("Feishu file upload failed.", code="upload_http", retryable=True) from exc
        payload = self._decode_response_payload(response, "upload")
        self._raise_for_feishu_error(payload, "upload")
        data = payload.get("data")
        file_token = data.get("file_token") if isinstance(data, dict) else None
        if not isinstance(file_token, str) or not file_token:
            raise FeishuIntegrationError("Feishu upload response was malformed.", code="upload_malformed")
        return file_token

    def root_folder_token(self) -> str:
        """Return the app identity's root folder token.

        Returns:
            Feishu Drive folder token for the application-owned root folder.

        Raises:
            FeishuIntegrationError: If metadata lookup fails or omits a token.
        """

        try:
            response = httpx.get(
                f"{self.api_base_url}/open-apis/drive/explorer/v2/root_folder/meta",
                headers=self._headers(),
                timeout=10,
            )
        except httpx.HTTPError as exc:
            raise FeishuIntegrationError("Feishu root folder metadata lookup failed.", code="root_http") from exc
        payload = self._decode_response_payload(response, "root")
        self._raise_for_feishu_error(payload, "root")
        data = payload.get("data")
        token = data.get("token") if isinstance(data, dict) else None
        if not isinstance(token, str) or not token:
            raise FeishuIntegrationError("Feishu root folder metadata response was malformed.", code="root_malformed")
        return token

    def set_tenant_readable(self, *, file_token: str) -> None:
        """Make the uploaded file link readable inside the tenant.

        Args:
            file_token: Feishu file token returned by upload.
        """

        self._set_link_share_entity(file_token=file_token, visibility=ShareVisibility.TENANT_READABLE)

    def close_link_sharing(self, *, file_token: str) -> None:
        """Best-effort close link sharing for a published file.

        Args:
            file_token: Feishu file token whose public link should be closed.
        """

        self._set_link_share_entity(file_token=file_token, visibility=ShareVisibility.CLOSED)

    def _set_link_share_entity(self, *, file_token: str, visibility: ShareVisibility) -> None:
        try:
            response = httpx.patch(
                f"{self.api_base_url}/open-apis/drive/v1/permissions/{file_token}/public",
                params={"type": "file"},
                headers=self._headers(),
                json={"external_access": False, "link_share_entity": visibility.value},
                timeout=10,
            )
        except httpx.HTTPError as exc:
            raise FeishuIntegrationError(
                "Feishu file permission update failed.", code="permission_http", retryable=True
            ) from exc
        payload = self._decode_response_payload(response, "permission")
        self._raise_for_feishu_error(payload, "permission")

    def file_url(self, *, file_token: str) -> str:
        """Return the tenant URL for an uploaded file.

        Args:
            file_token: Feishu file token returned by upload.

        Returns:
            Tenant-readable URL with query and hash stripped by the publisher.

        Raises:
            FeishuIntegrationError: If metadata lookup fails or omits a URL.
        """

        try:
            response = httpx.post(
                f"{self.api_base_url}/open-apis/drive/v1/metas/batch_query",
                headers=self._headers(),
                json={
                    "request_docs": [{"doc_token": file_token, "doc_type": "file"}],
                    "with_url": True,
                },
                timeout=10,
            )
        except httpx.HTTPError as exc:
            raise FeishuIntegrationError(
                "Feishu file metadata query failed.", code="meta_http", retryable=True
            ) from exc
        payload = self._decode_response_payload(response, "meta")
        self._raise_for_feishu_error(payload, "meta")
        data = payload.get("data")
        metas = data.get("metas") if isinstance(data, dict) else None
        first = metas[0] if isinstance(metas, list) and metas else None
        url = first.get("url") if isinstance(first, dict) else None
        if not isinstance(url, str) or not url:
            raise FeishuIntegrationError("Feishu metadata response did not include a URL.", code="meta_missing_url")
        return url

    def download_file(self, *, file_token: str) -> bytes:
        """Download one Feishu Drive file with the app tenant token.

        Args:
            file_token: Feishu file token parsed from a tenant-readable URL.

        Returns:
            Raw file bytes.

        Raises:
            FeishuIntegrationError: If Feishu rejects the download or returns
                an API error payload instead of file content.
        """

        quoted_token = quote(file_token, safe="")
        download_url = f"{self.api_base_url}/open-apis/drive/v1/files/{quoted_token}/download"
        try:
            with httpx.stream(
                "GET",
                download_url,
                headers=self._headers(),
                follow_redirects=True,
                timeout=30,
            ) as response:
                content_length = response.headers.get("content-length")
                if (
                    content_length is not None
                    and content_length.isdigit()
                    and int(content_length) > MAX_FEISHU_DOWNLOAD_BYTES
                ):
                    raise FeishuIntegrationError("Feishu download response was too large.", code="download_too_large")
                content_type = response.headers.get("content-type", "")
                content = self._read_download_response(response)
        except httpx.HTTPError as exc:
            raise FeishuIntegrationError("Feishu file download failed.", code="download_http", retryable=True) from exc
        if response.status_code >= 400:
            try:
                payload = response.json()
            except ValueError as exc:
                raise FeishuIntegrationError(
                    f"Feishu download HTTP request failed with status {response.status_code}.",
                    code=f"download_http_{response.status_code}",
                    retryable=response.status_code == 429 or response.status_code >= 500,
                ) from exc
            self._raise_for_feishu_error(payload, "download")
            raise FeishuIntegrationError(
                f"Feishu download HTTP request failed with status {response.status_code}.",
                code=f"download_http_{response.status_code}",
                retryable=response.status_code == 429 or response.status_code >= 500,
            )
        if "application/json" in content_type.lower():
            payload = self._decode_response_payload(response, "download")
            self._raise_for_feishu_error(payload, "download")
            raise FeishuIntegrationError("Feishu download response was malformed.", code="download_malformed")
        if not content:
            raise FeishuIntegrationError("Feishu download response was empty.", code="download_empty")
        return content

    def _read_download_response(self, response: httpx.Response) -> bytes:
        content = bytearray()
        for chunk in response.iter_bytes():
            content.extend(chunk)
            if len(content) > MAX_FEISHU_DOWNLOAD_BYTES:
                raise FeishuIntegrationError("Feishu download response was too large.", code="download_too_large")
        response._content = bytes(content)
        return bytes(content)

    def _headers(self) -> dict[str, str]:
        return {"authorization": f"Bearer {self.token_client.tenant_access_token()}"}

    def _decode_response_payload(self, response: httpx.Response, phase: str) -> dict[str, object]:
        try:
            payload = response.json()
        except ValueError as exc:
            if response.status_code >= 400:
                raise FeishuIntegrationError(
                    f"Feishu {phase} HTTP request failed with status {response.status_code}.",
                    code=f"{phase}_http_{response.status_code}",
                    retryable=response.status_code == 429 or response.status_code >= 500,
                ) from exc
            raise FeishuIntegrationError(f"Feishu {phase} response was malformed.", code=f"{phase}_malformed") from exc
        if response.status_code >= 400 and isinstance(payload, dict) and payload.get("code") in {None, 0}:
            raise FeishuIntegrationError(
                f"Feishu {phase} HTTP request failed with status {response.status_code}.",
                code=f"{phase}_http_{response.status_code}",
                retryable=response.status_code == 429 or response.status_code >= 500,
            )
        return payload if isinstance(payload, dict) else {"code": None, "msg": "malformed response"}

    def _raise_for_feishu_error(self, payload: object, phase: str) -> None:
        if not isinstance(payload, dict):
            raise FeishuIntegrationError(f"Feishu {phase} response was malformed.", code=f"{phase}_malformed")
        code = payload.get("code")
        if code == 0:
            return
        msg = payload.get("msg")
        logger.warning("Feishu %s failed with code %s", phase, code)
        raise FeishuIntegrationError(
            f"Feishu {phase} request was rejected: {_safe_feishu_message(msg)}",
            code=f"feishu_{code}",
            retryable=code in {99991400, 99991663, 1061001},
        )


class FeishuSharePublisher:
    """Publish a WorkRecorder share revision as a Feishu tenant-readable HTML file."""

    target = ShareTargetKind.FEISHU_DRIVE

    def __init__(self, *, drive: FeishuDriveClient, ids: IdFactory, clock: Clock) -> None:
        self.drive = drive
        self.ids = ids
        self.clock = clock

    def publish(self, *, share_id: str, revision: ShareRevision, html: bytes) -> ExternalShareTarget:
        """Upload HTML, set tenant-readable permissions, and return publication metadata.

        Args:
            share_id: Local WorkRecorder share id.
            revision: Immutable revision metadata containing the HTML filename.
            html: Human-readable share page bytes to upload.

        Returns:
            Published target metadata or a failed target with sanitized reason.
        """

        now = self.clock.now()
        target_id = self.ids.new("shr_tgt")
        file_name = revision.manifest.html_filename
        retry_count = 0
        file_token: str | None = None
        try:
            file_token = self._with_retry(lambda: self.drive.upload_html(file_name=file_name, content=html))
            self._with_retry(lambda: self.drive.set_tenant_readable(file_token=file_token))
            url = _sanitize_external_url(self._with_retry(lambda: self.drive.file_url(file_token=file_token)))
            return ExternalShareTarget(
                target_id=target_id,
                share_id=share_id,
                revision_id=revision.revision_id,
                target=ShareTargetKind.FEISHU_DRIVE,
                status=SharePublishStatus.PUBLISHED,
                provider_file_token=file_token,
                provider_url=url,
                visibility=ShareVisibility.TENANT_READABLE,
                retry_count=retry_count,
                created_at=now,
                updated_at=now,
            )
        except FeishuIntegrationError as exc:
            retry_count = int(getattr(exc, "attempts", 1))
            return ExternalShareTarget(
                target_id=target_id,
                share_id=share_id,
                revision_id=revision.revision_id,
                target=ShareTargetKind.FEISHU_DRIVE,
                status=SharePublishStatus.FAILED,
                visibility=ShareVisibility.TENANT_READABLE,
                provider_file_token=file_token,
                retry_count=retry_count,
                last_error_code=exc.code,
                last_error_message=str(exc),
                created_at=now,
                updated_at=now,
            )

    def revoke(self, *, target: ExternalShareTarget) -> ExternalShareTarget:
        """Best-effort close the Feishu file link.

        Args:
            target: Previously published Feishu target metadata.

        Returns:
            Updated target with revoked status or sanitized failure details.
        """

        now = self.clock.now()
        file_token = target.provider_file_token
        if not file_token:
            return target.model_copy(update={"status": SharePublishStatus.REVOKED, "updated_at": now})
        try:
            self._with_retry(lambda: self.drive.close_link_sharing(file_token=file_token))
            return target.model_copy(
                update={
                    "status": SharePublishStatus.REVOKED,
                    "visibility": ShareVisibility.CLOSED,
                    "updated_at": now,
                }
            )
        except FeishuIntegrationError as exc:
            return target.model_copy(
                update={
                    "last_error_code": exc.code,
                    "last_error_message": str(exc),
                    "updated_at": now,
                }
            )

    def _with_retry(self, operation: Callable[[], T]) -> T:
        last_error: FeishuIntegrationError | None = None
        for attempt in range(1, MAX_PUBLISH_ATTEMPTS + 1):
            try:
                return operation()
            except FeishuIntegrationError as exc:
                last_error = exc
                setattr(last_error, "attempts", attempt)
                if not exc.retryable or attempt >= MAX_PUBLISH_ATTEMPTS:
                    raise last_error from exc
                logger.info("Retrying Feishu share publish phase", extra={"attempt": attempt + 1, "code": exc.code})
        if last_error is not None:
            raise last_error
        raise FeishuIntegrationError("Feishu publish operation did not run.", code="publish_not_started")


def _sanitize_external_url(value: str) -> str:
    parts = urlsplit(value)
    if not parts.scheme:
        return value
    return urlunsplit((parts.scheme, _safe_netloc(parts), parts.path, "", ""))


def _safe_netloc(parts: object) -> str:
    host = getattr(parts, "hostname", None) or ""
    try:
        port = getattr(parts, "port", None)
    except ValueError:
        port = None
    return f"{host}:{port}" if port is not None else host


def _safe_feishu_message(value: object) -> str:
    if not isinstance(value, str) or not value.strip():
        return "unknown error"
    cleaned = _URL_RE.sub("[url:redacted]", value.strip())
    cleaned = _LOCAL_PATH_RE.sub("[path:redacted]", cleaned)
    return cleaned[:160]
