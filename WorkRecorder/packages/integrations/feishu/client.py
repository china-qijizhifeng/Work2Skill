from datetime import datetime, timedelta
from typing import Callable, TypeVar
from urllib.parse import quote, urlsplit, urlunsplit

import httpx

from packages.contracts import ExternalShareTarget, SharePublishStatus, ShareRevision, ShareTargetKind, ShareVisibility
