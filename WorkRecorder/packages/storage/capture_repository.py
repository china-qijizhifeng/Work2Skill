"""Atomic persistence for capture hot-path writes."""

from __future__ import annotations

from packages.contracts import Artifact, CaptureJob, ContextEvent

from .database import SQLiteDatabase


class CaptureRepository:
    """Persist a context event and its first artifact in one transaction."""

    def __init__(self, database: SQLiteDatabase) -> None:
        """Create a capture repository.

        Args:
            database: Database wrapper shared with other repositories.
        """

        self.database = database

    def save_event_and_artifact(self, *, event: ContextEvent, artifact: Artifact) -> tuple[ContextEvent, Artifact]:
        """Persist event and artifact atomically.

        Args:
            event: Context event created from the capture.
            artifact: First screenshot artifact owned by the event.

        Returns:
            Persisted event and artifact.
        """

        self.save_event_and_artifacts(event=event, artifacts=(artifact,))
        return event, artifact

    def save_event_and_artifacts(
        self, *, event: ContextEvent, artifacts: tuple[Artifact, ...]
    ) -> tuple[ContextEvent, tuple[Artifact, ...]]:
        """Persist event and artifacts atomically.

        Args:
            event: Context event created for the capture.
            artifacts: One or more artifacts owned by the event.

        Returns:
            Persisted event and artifact tuple.
        """

        return self.save_event_artifacts_jobs(event=event, artifacts=artifacts, jobs=())

    def save_event_artifacts_jobs(
        self, *, event: ContextEvent, artifacts: tuple[Artifact, ...], jobs: tuple[CaptureJob, ...]
    ) -> tuple[ContextEvent, tuple[Artifact, ...]]:
        """Persist event, artifacts, and capture jobs atomically.

        Args:
            event: Context event created for the capture.
            artifacts: Artifacts owned by the event.
            jobs: Durable enrichment/index jobs associated with the event.

        Returns:
            Persisted event and artifact tuple.
        """

        with self.database.transaction() as connection:
            connection.execute(
                """
                INSERT INTO context_events(event_id, status, payload, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?)
                ON CONFLICT(event_id) DO UPDATE SET
                  status = excluded.status,
                  payload = excluded.payload,
                  updated_at = excluded.updated_at
                """,
                (
                    event.event_id,
                    event.status.value,
                    event.model_dump_json(),
                    event.created_at.isoformat(),
                    event.updated_at.isoformat(),
                ),
            )
            for artifact in artifacts:
                connection.execute(
                    """
                    INSERT INTO artifacts(artifact_id, event_id, artifact_type, payload, created_at)
                    VALUES (?, ?, ?, ?, ?)
                    ON CONFLICT(artifact_id) DO UPDATE SET
                      event_id = excluded.event_id,
                      artifact_type = excluded.artifact_type,
                      payload = excluded.payload
                    """,
                    (
                        artifact.artifact_id,
                        artifact.event_id,
                        artifact.artifact_type.value,
                        artifact.model_dump_json(),
                        artifact.created_at.isoformat(),
                    ),
                )
            for job in jobs:
                connection.execute(
                    """
                    INSERT INTO capture_jobs(job_id, event_id, job_type, status, payload, created_at, updated_at)
                    VALUES (?, ?, ?, ?, ?, ?, ?)
                    ON CONFLICT(event_id, job_type) DO UPDATE SET
                      job_id = excluded.job_id,
                      status = excluded.status,
                      payload = excluded.payload,
                      updated_at = excluded.updated_at
                    """,
                    (
                        job.job_id,
                        job.event_id,
                        job.job_type.value,
                        job.status.value,
                        job.model_dump_json(),
                        job.created_at.isoformat(),
                        job.updated_at.isoformat(),
                    ),
                )
        return event, artifacts

    def find_by_trigger_id(self, trigger_id: str) -> tuple[ContextEvent, Artifact] | None:
        """Return an existing capture saved from the same trigger.

        Args:
            trigger_id: Stable trigger identifier generated by the capture shell.

        Returns:
            Existing event and first artifact when the trigger was already
            persisted, otherwise ``None``.
        """

        with self.database.transaction() as connection:
            row = connection.execute(
                """
                SELECT
                    context_events.payload AS event_payload,
                    artifacts.payload AS artifact_payload
                FROM context_events
                JOIN artifacts ON artifacts.event_id = context_events.event_id
                WHERE json_extract(context_events.payload, '$.trigger.trigger_id') = ?
                ORDER BY artifacts.created_at ASC
                LIMIT 1
                """,
                (trigger_id,),
            ).fetchone()
        if row is None:
            return None
        return (
            ContextEvent.model_validate_json(str(row["event_payload"])),
            Artifact.model_validate_json(str(row["artifact_payload"])),
        )

    def find_artifacts_by_trigger_id(self, trigger_id: str) -> tuple[ContextEvent, tuple[Artifact, ...]] | None:
        """Return an existing capture and all artifacts for an idempotent trigger.

        Args:
            trigger_id: Stable trigger identifier generated by the capture shell.

        Returns:
            Existing event and all artifacts ordered by creation time, otherwise
            ``None``.
        """

        with self.database.transaction() as connection:
            rows = connection.execute(
                """
                SELECT
                    context_events.payload AS event_payload,
                    artifacts.payload AS artifact_payload
                FROM context_events
                JOIN artifacts ON artifacts.event_id = context_events.event_id
                WHERE json_extract(context_events.payload, '$.trigger.trigger_id') = ?
                ORDER BY artifacts.created_at ASC
                """,
                (trigger_id,),
            ).fetchall()
        if not rows:
            return None
        event = ContextEvent.model_validate_json(str(rows[0]["event_payload"]))
        artifacts = tuple(Artifact.model_validate_json(str(row["artifact_payload"])) for row in rows)
        return event, artifacts
